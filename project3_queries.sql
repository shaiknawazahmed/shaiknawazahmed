-- Business &amp; Marketing Sales Analysis

-- ============================================





-- 1. Total Sales



SELECT SUM(SALES_AMOUNT) AS TOTAL_SALES

FROM SALES;





-- 2. Average Sale



SELECT AVG(SALES_AMOUNT) AS AVERAGE_SALE

FROM SALES;





-- 3. Highest Sale



SELECT MAX(SALES_AMOUNT) AS HIGHEST_SALE

FROM SALES;





-- 4. Lowest Sale



SELECT MIN(SALES_AMOUNT) AS LOWEST_SALE

FROM SALES;





-- 5. Total Number of Sales Transactions



SELECT COUNT(*) AS TOTAL_SALES_TRANSACTIONS

FROM SALES;





-- 6. Total Quantity Sold



SELECT SUM(QUANTITY) AS TOTAL_QUANTITY

FROM SALES;





-- 7. Product-wise Sales



SELECT

    P.PRODUCT_NAME,

    SUM(S.SALES_AMOUNT) AS TOTAL_SALES

FROM SALES S

JOIN PRODUCTS P

ON S.PRODUCT_ID = P.PRODUCT_ID

GROUP BY P.PRODUCT_NAME

ORDER BY TOTAL_SALES DESC;





-- 8. Category-wise Sales



SELECT

    P.CATEGORY,

