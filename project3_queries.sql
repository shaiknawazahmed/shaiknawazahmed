-- 18. Sales Above 30,000



SELECT *

FROM SALES

WHERE SALES_AMOUNT &gt; 30000

ORDER BY SALES_AMOUNT DESC;





-- 19. Customers with Sales Above 50,000



SELECT

    C.CUSTOMER_NAME,

    SUM(S.SALES_AMOUNT) AS TOTAL_SALES

FROM SALES S

JOIN CUSTOMERS C

ON S.CUSTOMER_ID = C.CUSTOMER_ID

GROUP BY C.CUSTOMER_NAME

HAVING SUM(S.SALES_AMOUNT) &gt; 50000

ORDER BY TOTAL_SALES DESC;





