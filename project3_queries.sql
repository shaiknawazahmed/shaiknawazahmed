-- 30. Complete Business Sales Analysis



SELECT

    C.CUSTOMER_NAME,

    C.CITY,

    C.CUSTOMER_TYPE,

    P.PRODUCT_NAME,

    P.CATEGORY,

    M.CAMPAIGN_NAME,

    M.CHANNEL,

    S.QUANTITY,

    S.SALES_AMOUNT,

    S.SALE_DATE

FROM SALES S

JOIN CUSTOMERS C

ON S.CUSTOMER_ID = C.CUSTOMER_ID

JOIN PRODUCTS P

ON S.PRODUCT_ID = P.PRODUCT_ID

JOIN CAMPAIGNS M

ON S.CAMPAIGN_ID = M.CAMPAIGN_ID

ORDER BY S.SALES_AMOUNT DESC;
