-- 21. Monthly Sales



SELECT

    strftime('%Y-%m', SALE_DATE) AS MONTH,

    SUM(SALES_AMOUNT) AS TOTAL_SALES

FROM SALES

GROUP BY MONTH

ORDER BY MONTH;





-- 22. Monthly Transaction Count



SELECT

    strftime('%Y-%m', SALE_DATE) AS MONTH,

    COUNT(*) AS TOTAL_TRANSACTIONS

FROM SALES

GROUP BY MONTH

ORDER BY MONTH;





