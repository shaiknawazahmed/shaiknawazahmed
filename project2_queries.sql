


-- 1. Total Sales

SELECT SUM(SALES) AS TOTAL_SALES

FROM PERFORMANCE;



-- 2. Average Sales

SELECT AVG(SALES) AS AVERAGE_SALES

FROM PERFORMANCE;



-- 3. Highest Sale

SELECT MAX(SALES) AS HIGHEST_SALE

FROM PERFORMANCE;



-- 4. Lowest Sale

SELECT MIN(SALES) AS LOWEST_SALE

FROM PERFORMANCE;



-- 5. Total Performance Records

SELECT COUNT(*) AS TOTAL_RECORDS

FROM PERFORMANCE;



-- 6. Employee-wise Total Sales

SELECT E.NAME, SUM(P.SALES) AS TOTAL_SALES

FROM PERFORMANCE P

JOIN EMPLOYEES E ON P.EMPLOYEE_ID = E.EMPLOYEE_ID

GROUP BY E.NAME;



-- 7. Department-wise Total Sales

SELECT E.DEPARTMENT, SUM(P.SALES) AS TOTAL_SALES

FROM PERFORMANCE P

JOIN EMPLOYEES E ON P.EMPLOYEE_ID = E.EMPLOYEE_ID

GROUP BY E.DEPARTMENT;



-- 8. Department-wise Average Rating

SELECT E.DEPARTMENT, AVG(P.RATING) AS AVERAGE_RATING

FROM PERFORMANCE P

JOIN EMPLOYEES E ON P.EMPLOYEE_ID = E.EMPLOYEE_ID

GROUP BY E.DEPARTMENT;



-- 9. January Sales

SELECT SUM(SALES) AS JANUARY_SALES

FROM PERFORMANCE

WHERE MONTH = 'January';



-- 10. February Sales

SELECT SUM(SALES) AS FEBRUARY_SALES

FROM PERFORMANCE

WHERE MONTH = 'February';



-- 11. Sales Above 50,000

SELECT *

FROM PERFORMANCE

WHERE SALES &gt; 50000

ORDER BY SALES DESC;



-- 12. Employees with Total Sales Above 90,000

SELECT E.NAME, SUM(P.SALES) AS TOTAL_SALES

FROM PERFORMANCE P

JOIN EMPLOYEES E ON P.EMPLOYEE_ID = E.EMPLOYEE_ID

GROUP BY E.NAME

HAVING SUM(P.SALES) &gt; 90000;



-- 13. Employee + Department + Sales

SELECT E.NAME, E.DEPARTMENT, P.MONTH, P.SALES, P.RATING

FROM PERFORMANCE P

JOIN EMPLOYEES E ON P.EMPLOYEE_ID = E.EMPLOYEE_ID;



-- 14. Top Employee

SELECT E.NAME, SUM(P.SALES) AS TOTAL_SALES

FROM PERFORMANCE P

JOIN EMPLOYEES E ON P.EMPLOYEE_ID = E.EMPLOYEE_ID

GROUP BY E.NAME

ORDER BY TOTAL_SALES DESC

LIMIT 1;



-- 15. Top Department

SELECT E.DEPARTMENT, SUM(P.SALES) AS TOTAL_SALES

FROM PERFORMANCE P

JOIN EMPLOYEES E ON P.EMPLOYEE_ID = E.EMPLOYEE_ID

GROUP BY E.DEPARTMENT

ORDER BY TOTAL_SALES DESC

LIMIT 1;



-- 16. Highest Rated Employee

SELECT E.NAME, AVG(P.RATING) AS AVERAGE_RATING

FROM PERFORMANCE P

JOIN EMPLOYEES E ON P.EMPLOYEE_ID = E.EMPLOYEE_ID

GROUP BY E.NAME

ORDER BY AVERAGE_RATING DESC

LIMIT 1;



-- 17. City-wise Sales

SELECT E.CITY, SUM(P.SALES) AS TOTAL_SALES

FROM PERFORMANCE P

JOIN EMPLOYEES E ON P.EMPLOYEE_ID = E.EMPLOYEE_ID

GROUP BY E.CITY

ORDER BY TOTAL_SALES DESC;



-- 18. Department Sales vs Target

SELECT E.DEPARTMENT, SUM(P.SALES) AS TOTAL_SALES, D.TARGET

FROM PERFORMANCE P

JOIN EMPLOYEES E ON P.EMPLOYEE_ID = E.EMPLOYEE_ID

JOIN DEPARTMENTS D ON E.DEPARTMENT = D.DEPARTMENT

GROUP BY E.DEPARTMENT, D.TARGET;



-- 19. Employees with Rating 5

SELECT E.NAME, P.MONTH, P.RATING

FROM PERFORMANCE P

JOIN EMPLOYEES E ON P.EMPLOYEE_ID = E.EMPLOYEE_ID

WHERE P.RATING = 5;



-- 20. Top 3 Employees by Total Sales

SELECT E.NAME, SUM(P.SALES) AS TOTAL_SALES

FROM PERFORMANCE P

JOIN EMPLOYEES E ON P.EMPLOYEE_ID = E.EMPLOYEE_ID

GROUP BY E.NAME

ORDER BY TOTAL_SALES DESC

LIMIT 3;
